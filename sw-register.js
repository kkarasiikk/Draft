// ---- Реєстрація Service Worker ----
//
// Живе в корені й підключається всіма пʼятьма сторінками (як scroll-lock.js
// та unsaved-guard.js): досі ці рядки лежали пʼятьма копіями на початку
// кожного app.js — тобто в найкращому місці, щоб розійтись і щоб правку
// забули в одному з файлів.
//
// Реєструємо файлом, а не інлайн у <script>, щоб CSP міг забороняти
// інлайн-скрипти (script-src без 'unsafe-inline') без винятків. Шлях
// 'service-worker.js' відносний до СТОРІНКИ, а не до цього файлу, тож у
// корені він знаходить свій воркер, а в розділі — свій.
//
// САМОПЕРЕЗАВАНТАЖЕННЯ ПІСЛЯ ОНОВЛЕННЯ ТУТ СВІДОМО НЕМАЄ.
//
// Спокуса очевидна: щойно новий воркер перебирає керування — перезавантажити
// сторінку, щоб людина побачила зміни одразу. На перевірці це виявилось
// гіршим за проблему: оновлення воркера починається з тієї ж навігації, тож
// перезавантаження влучало посеред завантаження й обривало його — половина
// запитів лишалась зі статусом «скасовано», а замість свіжої версії
// показувалась порожня сторінка. Затримка до події `load` не рятувала.
//
// Причина «оновив — змін не бачу» була не в цьому, а в тому, що sw-core.js
// шукав відповідь у ВСІХ кешах походження, і старий вигравав у нового (див.
// matchOwn там). Це виправлено, і тепер найгірше, що буває, — свіжу версію
// видно з наступного відкриття, а не «ніколи».
(function () {
  'use strict';

  if (!('serviceWorker' in navigator)) return;

  window.addEventListener('load', function () {
    // updateViaCache:'none' — щоб і сам воркер, і його importScripts('sw-core.js')
    // бралися з мережі, а не з HTTP-кешу браузера. За замовчуванням ('imports')
    // імпорти віддаються з кешу, і оболонка, яку тримає sw-core, лишалась би
    // старою навіть після деплою: саме в тому файлі живе версія збірки.
    navigator.serviceWorker.register('service-worker.js', { updateViaCache: 'none' })
      .catch(function () {});
  });
})();
